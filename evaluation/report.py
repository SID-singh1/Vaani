"""Builds evaluation/benchmark_report.md from every saved run in evaluation/results/."""

from __future__ import annotations

import json
from pathlib import Path
from statistics import mean

from .metrics import percentile

EVAL_DIR = Path(__file__).resolve().parent
RESULTS_DIR = EVAL_DIR / "results"
REPORT_PATH = EVAL_DIR / "benchmark_report.md"


def _mean(rows: list[dict], key: str) -> float | None:
    values = [r[key] for r in rows if r.get(key) is not None]
    return mean(values) if values else None


def _judge_mean(rows: list[dict], key: str) -> float | None:
    values = [r["judge"][key] for r in rows if r.get("judge") and r["judge"].get(key) is not None]
    return mean(values) if values else None


def _fmt(value, suffix="", scale=1.0, digits=1) -> str:
    return "–" if value is None else f"{value * scale:.{digits}f}{suffix}"


def summarize(rows: list[dict]) -> dict:
    ok = [r for r in rows if "error" not in r]
    judged = [r for r in ok if r.get("judge")]
    totals = [r["total_sec"] for r in ok]
    return {
        "n": len(ok),
        "failed": len(rows) - len(ok),
        "audio_min": sum(r["duration_sec"] for r in ok) / 60,
        "wer": _mean(ok, "wer"),
        "cer": _mean(ok, "cer"),
        "hwer": _mean(ok, "hwer"),
        "recall": _judge_mean(ok, "recall"),
        "precision": _judge_mean(ok, "precision"),
        "hallucinated": (sum(1 for r in judged if r["judge"]["summary_unsupported_claims"]) / len(judged))
        if judged else None,
        "p50": percentile(totals, 50),
        "p95": percentile(totals, 95),
        "rtf": _mean(ok, "rtf"),
    }


def write_report() -> Path:
    runs = [json.loads(p.read_text(encoding="utf-8")) for p in sorted(RESULTS_DIR.glob("*.json"))]
    lines = [
        "# Vaani evaluation report",
        "",
        "_Generated by `scripts/run_eval_suite.py`. Methodology: [evaluation/README.md](README.md)._",
        "",
        "**Read this first.** Clips marked `human` are real recordings. Clips marked `tts` were synthesized "
        "with Google TTS from their own reference text, so they are clean, single-speaker and optimistic; use "
        "them to compare configurations, not as real-world accuracy. WER is the strict metric; hWER forgives "
        "Hinglish spelling variants and number formats (see metrics.py) and must not be quoted without WER.",
        "",
    ]
    for source in ("human", "tts"):
        lines += [
            f"## {'Real recordings (human)' if source == 'human' else 'Synthetic clips (tts)'}",
            "",
            "| Configuration | Clips | Audio | WER | hWER | CER | Action recall | Action precision | "
            "Summaries w/ unsupported claims | Latency p50 / p95 | Real-time factor |",
            "|:--|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|",
        ]
        for run in runs:
            rows = [r for r in run["rows"] if r.get("source") == source]
            if not rows:
                continue
            s = summarize(rows)
            cfg = run["config"]
            label = f"**{cfg['name']}**<br><sub>{' → '.join(cfg['llms'])}</sub>"
            failed = f" ({s['failed']} failed)" if s["failed"] else ""
            lines.append(
                f"| {label} | {s['n']}{failed} | {s['audio_min']:.1f} min "
                f"| {_fmt(s['wer'], '%')} | {_fmt(s['hwer'], '%')} | {_fmt(s['cer'], '%')} "
                f"| {_fmt(s['recall'], '%', 100, 0)} | {_fmt(s['precision'], '%', 100, 0)} "
                f"| {_fmt(s['hallucinated'], '%', 100, 0)} | {_fmt(s['p50'], 's')} / {_fmt(s['p95'], 's')} "
                f"| {_fmt(s['rtf'], '×', 1, 2)} |"
            )
        lines.append("")

    lines += ["## Runs", "", "| Configuration | Speech-to-text | LLMs | Judge | Commit | Date |", "|:--|:--|:--|:--|:--|:--|"]
    for run in runs:
        cfg = run["config"]
        cached = " (cached transcripts)" if cfg.get("asr_cached") else ""
        lines.append(
            f"| {cfg['name']} | {cfg['asr']}{cached} | {', '.join(cfg['llms'])} | {cfg.get('judge') or '–'} "
            f"| `{cfg['git_commit']}` | {cfg['date']} |"
        )
    lines += [
        "",
        "Latency is measured from the evaluation machine and includes network time to the providers. "
        "Real-time factor = processing time / audio duration (below 1 means faster than real time).",
        "",
    ]
    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")
    return REPORT_PATH
